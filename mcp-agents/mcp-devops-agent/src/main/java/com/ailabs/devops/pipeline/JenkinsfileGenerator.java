package com.ailabs.devops.pipeline;

import java.util.LinkedHashMap;
import java.util.Map;
import java.util.regex.Pattern;

/**
 * Renders a {@link PipelineSpec} as a declarative Jenkinsfile.
 *
 * <p>Every user-provided value is validated and placed in the {@code environment} block as a
 * single-quoted Groovy literal, and shell steps use {@code '''} strings that refer to {@code $VARS}.
 * Nothing is Groovy-interpolated, so values cannot inject Groovy or shell, and secrets only ever
 * appear as Jenkins credential bindings.
 */
public final class JenkinsfileGenerator {

    private static final Pattern K8S_NAME = Pattern.compile("^[a-z0-9]([-a-z0-9]{0,61}[a-z0-9])?$");
    private static final Pattern IMAGE = Pattern.compile("^[a-z0-9]+([._-][a-z0-9]+)*(:[0-9]+)?(/[a-z0-9]+([._-][a-z0-9]+)*)*$");
    private static final Pattern CRED_ID = Pattern.compile("^[A-Za-z0-9._-]{1,128}$");
    private static final Pattern BRANCH = Pattern.compile("^[A-Za-z0-9._/-]{1,200}$");
    private static final Pattern REL_PATH = Pattern.compile("^[A-Za-z0-9._/-]{1,200}$");
    private static final Pattern GIT_URL = Pattern.compile("^(https?://|ssh://|git@)[^\\s'\"\\\\$`]+$");
    private static final Pattern HTTP_URL = Pattern.compile("^https?://[^\\s'\"\\\\$`]+$");
    private static final Pattern LABEL = Pattern.compile("^[A-Za-z0-9 ._&|!()-]{1,100}$");

    private JenkinsfileGenerator() {}

    public static String generate(PipelineSpec s) {
        String tool = or(s.buildTool(), "maven").toLowerCase();
        String image = require(s.image(), IMAGE, "image");
        String deployment = or(s.deployment(), image.substring(image.lastIndexOf('/') + 1).replaceAll("[^a-z0-9-]", "-"));
        boolean deploy = !Boolean.FALSE.equals(s.deploy());
        boolean tests = !Boolean.FALSE.equals(s.runTests());
        boolean rollback = !Boolean.FALSE.equals(s.rollbackOnFailure());
        boolean health = deploy && s.healthUrl() != null && !s.healthUrl().isBlank();

        Map<String, String> env = new LinkedHashMap<>();
        env.put("GIT_URL_", require(s.gitUrl(), GIT_URL, "gitUrl"));
        env.put("GIT_BRANCH_", require(or(s.gitBranch(), "main"), BRANCH, "gitBranch"));
        env.put("IMAGE", image);
        env.put("DOCKERFILE", require(or(s.dockerfile(), "Dockerfile"), REL_PATH, "dockerfile"));
        env.put("DOCKER_CONTEXT", require(or(s.dockerContext(), "."), REL_PATH, "dockerContext"));
        env.put("REGISTRY", registryOf(image));
        if (deploy) {
            env.put("K8S_NAMESPACE", require(or(s.namespace(), "default"), K8S_NAME, "namespace"));
            env.put("K8S_DEPLOYMENT", require(deployment, K8S_NAME, "deployment"));
            env.put("K8S_CONTAINER", require(or(s.container(), deployment), K8S_NAME, "container"));
            if (s.manifestsPath() != null && !s.manifestsPath().isBlank()) {
                env.put("K8S_MANIFESTS", require(s.manifestsPath(), REL_PATH, "manifestsPath"));
            }
        }
        if (health) {
            env.put("HEALTH_URL", require(s.healthUrl(), HTTP_URL, "healthUrl"));
            env.put("HEALTH_STATUS", String.valueOf(range(s.healthExpectedStatus(), 200, 100, 599)));
            env.put("HEALTH_RETRIES", String.valueOf(range(s.healthRetries(), 12, 1, 100)));
            env.put("HEALTH_INTERVAL", String.valueOf(range(s.healthIntervalSeconds(), 10, 1, 300)));
        }
        String dockerCred = require(or(s.dockerCredentialsId(), "dockerhub"), CRED_ID, "dockerCredentialsId");
        String kubeCred = require(or(s.kubeconfigCredentialsId(), "kubeconfig"), CRED_ID, "kubeconfigCredentialsId");
        String gitCred = s.gitCredentialsId() == null || s.gitCredentialsId().isBlank() ? null
                : require(s.gitCredentialsId(), CRED_ID, "gitCredentialsId");

        String[] cmds = commands(tool, s.buildCommand(), s.testCommand());

        StringBuilder j = new StringBuilder();
        j.append("// Generated by mcp-devops-agent. Stages: checkout, build, test, image, deploy, health check.\n");
        j.append("pipeline {\n");
        if (s.agentLabel() != null && !s.agentLabel().isBlank()) {
            j.append("    agent { label ").append(q(require(s.agentLabel(), LABEL, "agentLabel"))).append(" }\n");
        } else {
            j.append("    agent any\n");
        }
        j.append("    options {\n")
         .append("        disableConcurrentBuilds()\n")
         .append("        buildDiscarder(logRotator(numToKeepStr: '20'))\n")
         .append("        timeout(time: 60, unit: 'MINUTES')\n")
         .append("    }\n");
        j.append("    environment {\n");
        env.forEach((k, v) -> j.append("        ").append(k).append(" = ").append(q(v)).append('\n'));
        j.append("    }\n");
        j.append("    stages {\n");

        // Checkout
        j.append("        stage('Checkout') {\n            steps {\n");
        j.append("                git url: env.GIT_URL_, branch: env.GIT_BRANCH_");
        if (gitCred != null) {
            j.append(", credentialsId: ").append(q(gitCred));
        }
        j.append("\n");
        j.append("                script {\n")
         .append("                    env.GIT_SHORT = sh(returnStdout: true, script: 'git rev-parse --short HEAD').trim()\n")
         .append("                    env.IMAGE_TAG = \"${env.BUILD_NUMBER}-${env.GIT_SHORT}\"\n")
         .append("                }\n")
         .append("                echo \"Building ${env.IMAGE}:${env.IMAGE_TAG}\"\n");
        j.append("            }\n        }\n");

        if (cmds[0] != null) {
            stage(j, "Build", cmds[0]);
        }
        if (tests && cmds[1] != null) {
            stage(j, "Test", cmds[1]);
        }

        // Image
        j.append("        stage('Docker Build & Push') {\n            steps {\n");
        j.append("                withCredentials([usernamePassword(credentialsId: ").append(q(dockerCred))
         .append(", usernameVariable: 'REG_USER', passwordVariable: 'REG_PASS')]) {\n");
        j.append("                    sh '''\n")
         .append("                        set -eu\n")
         .append("                        echo \"$REG_PASS\" | docker login -u \"$REG_USER\" --password-stdin $REGISTRY\n")
         .append("                        docker build -t \"$IMAGE:$IMAGE_TAG\" -f \"$DOCKERFILE\" \"$DOCKER_CONTEXT\"\n")
         .append("                        docker push \"$IMAGE:$IMAGE_TAG\"\n");
        if (Boolean.TRUE.equals(s.pushLatest())) {
            j.append("                        docker tag \"$IMAGE:$IMAGE_TAG\" \"$IMAGE:latest\"\n")
             .append("                        docker push \"$IMAGE:latest\"\n");
        }
        j.append("                        docker logout $REGISTRY || true\n")
         .append("                    '''\n")
         .append("                }\n");
        j.append("            }\n        }\n");

        if (deploy) {
            j.append("        stage('Deploy to Kubernetes') {\n            steps {\n");
            j.append("                withCredentials([file(credentialsId: ").append(q(kubeCred)).append(", variable: 'KUBECONFIG')]) {\n");
            j.append("                    script { env.DEPLOY_STARTED = 'true' }\n");
            j.append("                    sh '''\n")
             .append("                        set -eu\n");
            if (env.containsKey("K8S_MANIFESTS")) {
                j.append("                        kubectl -n \"$K8S_NAMESPACE\" apply -f \"$K8S_MANIFESTS\"\n");
            }
            j.append("                        kubectl -n \"$K8S_NAMESPACE\" set image deployment/\"$K8S_DEPLOYMENT\" \"$K8S_CONTAINER=$IMAGE:$IMAGE_TAG\"\n")
             .append("                        kubectl -n \"$K8S_NAMESPACE\" rollout status deployment/\"$K8S_DEPLOYMENT\" --timeout=300s\n")
             .append("                    '''\n")
             .append("                }\n");
            j.append("            }\n        }\n");
        }

        if (health) {
            j.append("        stage('Health Check') {\n            steps {\n");
            j.append("                sh '''\n")
             .append("                    set -u\n")
             .append("                    i=1\n")
             .append("                    while [ \"$i\" -le \"$HEALTH_RETRIES\" ]; do\n")
             .append("                        code=$(curl -s -o /dev/null -w '%{http_code}' --max-time 5 \"$HEALTH_URL\" || echo 000)\n")
             .append("                        echo \"health attempt $i: HTTP $code\"\n")
             .append("                        if [ \"$code\" = \"$HEALTH_STATUS\" ]; then exit 0; fi\n")
             .append("                        i=$((i + 1))\n")
             .append("                        sleep \"$HEALTH_INTERVAL\"\n")
             .append("                    done\n")
             .append("                    echo \"$HEALTH_URL did not return $HEALTH_STATUS\"\n")
             .append("                    exit 1\n")
             .append("                '''\n");
            j.append("            }\n        }\n");
        }
        j.append("    }\n");

        j.append("    post {\n");
        if (deploy && rollback) {
            j.append("        failure {\n")
             .append("            script {\n")
             .append("                if (env.DEPLOY_STARTED == 'true') {\n")
             .append("                    withCredentials([file(credentialsId: ").append(q(kubeCred)).append(", variable: 'KUBECONFIG')]) {\n")
             .append("                        sh 'kubectl -n \"$K8S_NAMESPACE\" rollout undo deployment/\"$K8S_DEPLOYMENT\" || true'\n")
             .append("                    }\n")
             .append("                    echo 'Deployment rolled back to the previous revision'\n")
             .append("                }\n")
             .append("            }\n")
             .append("        }\n");
        }
        j.append("        success {\n")
         .append("            echo \"Released ${env.IMAGE}:${env.IMAGE_TAG}\"\n")
         .append("        }\n");
        j.append("    }\n");
        j.append("}\n");
        return j.toString();
    }

    private static void stage(StringBuilder j, String name, String command) {
        j.append("        stage('").append(name).append("') {\n            steps {\n");
        j.append("                sh ").append(q(command)).append("\n");
        j.append("            }\n        }\n");
    }

    /** {build, test}; null means the stage is skipped. */
    static String[] commands(String tool, String buildOverride, String testOverride) {
        String build;
        String test;
        switch (tool) {
            case "maven" -> {
                build = "if [ -x ./mvnw ]; then ./mvnw -B -DskipTests package; else mvn -B -DskipTests package; fi";
                test = "if [ -x ./mvnw ]; then ./mvnw -B test; else mvn -B test; fi";
            }
            case "gradle" -> {
                build = "if [ -x ./gradlew ]; then ./gradlew --no-daemon assemble; else gradle --no-daemon assemble; fi";
                test = "if [ -x ./gradlew ]; then ./gradlew --no-daemon test; else gradle --no-daemon test; fi";
            }
            case "npm" -> {
                build = "npm ci && npm run build --if-present";
                test = "npm test";
            }
            case "go" -> {
                build = "go build ./...";
                test = "go test ./...";
            }
            case "none" -> {
                build = null;
                test = null;
            }
            default -> throw new IllegalArgumentException("buildTool must be maven, gradle, npm, go or none; got " + tool);
        }
        if (buildOverride != null && !buildOverride.isBlank()) {
            build = buildOverride;
        }
        if (testOverride != null && !testOverride.isBlank()) {
            test = testOverride;
        }
        return new String[] {build, test};
    }

    /** Registry host for docker login; empty for Docker Hub. */
    static String registryOf(String image) {
        int slash = image.indexOf('/');
        if (slash > 0) {
            String first = image.substring(0, slash);
            if (first.contains(".") || first.contains(":") || first.equals("localhost")) {
                return first;
            }
        }
        return "";
    }

    /** Single-quoted Groovy string literal. */
    static String q(String s) {
        return "'" + s.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n") + "'";
    }

    private static String require(String value, Pattern p, String field) {
        if (value == null || !p.matcher(value).matches()) {
            throw new IllegalArgumentException("Invalid " + field + ": '" + value + "'");
        }
        return value;
    }

    private static String or(String v, String dflt) {
        return v == null || v.isBlank() ? dflt : v.trim();
    }

    private static int range(Integer v, int dflt, int min, int max) {
        int x = v == null ? dflt : v;
        if (x < min || x > max) {
            throw new IllegalArgumentException("Value " + x + " outside " + min + ".." + max);
        }
        return x;
    }
}
